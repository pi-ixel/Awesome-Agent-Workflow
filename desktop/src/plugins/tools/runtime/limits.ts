/**
 * 体积与超时的唯一出处（前端这一份）。
 *
 * 与 `src-tauri/src/tools/limits.rs` 的 `LIMITS` 是同一组数字。分工是：
 *
 * - **前端**用它们做作者能看见的校验：导入的包多大、源码文件多少个、导出 ZIP
 *   多大。误差只会导致"这次导入被拦下"，作者能立刻看到原因。
 * - **Rust** 用它们做真正的执行限制：动作多久算超时、返回多大算超限、存储能写
 *   多少。误差的后果是工具跑到一半报错。
 *
 * 两边不一致时，先炸的是工具而不是测试——所以 `limits.test.ts` 会把
 * `limits.rs` 里的数字抠出来逐项比对。
 *
 * # 为什么不是"只留一份，另一份读文件"
 *
 * 前端跑在 WebView 里，读不了 Rust 源码；Rust 也不能在编译期 import TS。想让
 * 它们共享一份，只能靠构建期生成代码，而那样又会出现"生成的产物没提交/没更新"
 * 的新失败模式。两条独立的、被测试钉住的常量，比一条会断的管道可靠。
 */
export const toolLimits = {
  /** 动作超时（毫秒）。载体无关：页面与进程同一套语义。 */
  actionTimeoutMs: 20_000,
  /** 动作返回值上限（字节）。超了直接报错，不截断。 */
  resultBytes: 512 * 1024,
  /** 每个工具的键值存储上限。 */
  storeBytes: 5 * 1024 * 1024,
  /** 清单里 `sourceFiles` 最多几个文件。 */
  sourceFiles: 512,
  /** 清单里 `sourceFiles` 合计字节数。 */
  sourceBytes: 4 * 1024 * 1024,
  /** 单个工具包（`html` 快照 + 清单）上限。 */
  packageBytes: 4 * 1024 * 1024,
  /** 整包 ZIP（源码 + `bin/`）上限。 */
  archiveBytes: 32 * 1024 * 1024,
} as const;
